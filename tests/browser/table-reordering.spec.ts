import { expect, test } from '@playwright/test'

test('keyboard menu reorders a body row and native Undo/Redo restores it', async ({ page }) => {
  await page.goto('/?story=basics--table&mode=preview')
  const cells = page.locator('tbody [contenteditable=true]')
  await expect(cells).toHaveCount(9)
  const original = await cells.allTextContents()
  await cells.nth(3).click()
  await page.getByRole('button', { name: 'Row menu', exact: true }).nth(1).focus()
  await page.keyboard.press('Enter')
  const move = page.getByRole('button', { name: 'Move row down', exact: true })
  await expect(move).toBeVisible()
  await move.focus()
  await page.keyboard.press('Enter')
  await expect(cells.nth(6)).toHaveText(original[3])
  await expect(cells.nth(6)).toBeFocused()
  await page.keyboard.press('ControlOrMeta+z')
  await expect.poll(() => cells.allTextContents()).toEqual(original)
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(cells.nth(6)).toHaveText(original[3])
})

test('column move closes its popover before changing geometry and preserves focus', async ({ page }) => {
  await page.goto('/?story=basics--table&mode=preview')
  const cells = page.locator('tbody [contenteditable=true]')
  await expect(cells).toHaveCount(9)
  const original = await cells.allTextContents()
  await cells.nth(4).click()
  await page.getByRole('button', { name: 'Column menu', exact: true }).nth(1).click()
  await page.getByRole('button', { name: 'Move column left', exact: true }).click()
  await expect(cells.nth(3)).toHaveText(original[4])
  await expect(cells.nth(3)).toBeFocused()
  await page.keyboard.press('ControlOrMeta+z')
  await expect.poll(() => cells.allTextContents()).toEqual(original)
})
